import { STAGE_LABEL, type DiseaseType, type UseCaseScenario } from "@/lib/types/case";

/**
 * 各阶段建议覆盖的字段类目——参考实际病例样本（含ECOG评分/伴随阴性症状/体格检查/
 * 实验室检查/影像学检查/用药选择依据/治疗时间线/病例小结等）整理，比早期版本更贴近
 * 真实临床病例讨论需要的颗粒度。"相关检查"与"诊断"拆为两个并列阶段——前者是检查类
 * 原始发现，后者是诊断结论本身，不要混在一起。
 */
const FIELD_TEMPLATE = `
【就诊 visit】性别、年龄、患者标识、体力状态评分（ECOG/PS）、首次就诊时间、主诉、现病史、
伴随阴性症状（原文提到的"无XX"类阴性症状，单独列出）、既往病史、手术外伤史、输血史、
个人史及家族史、用药史、过敏史

【相关检查 relevant_exams】体格检查（含生命体征及查体阳性/阴性发现）、实验室检查（含血常规/
生化/肿瘤标志物/病理与分子分型等）、影像学检查（含CT/MRI/超声等所见）——只按这三个子类目
输出，不要再拆成"生命体征""阳性体征""阴性体征""常规检查""生化检查""肿瘤标志物""病理"
"影像学"这些更细碎的标签

【诊断 diagnosis】主要诊断、次要诊断（原"副诊断"）、诊断依据——只包含这三项，不要在这里
重复相关检查阶段已经覆盖的检查类内容

【治疗经过 treatment_course】治疗目标、治疗方案、用药信息（逐个药物的剂量/频次/途径/疗程）、
用药选择依据（指南/研究证据支持治疗选择的理由）、联合方案、疗程时长、治疗节点（必须按原文
日期或先后顺序拆成多条独立字段，label依次写“治疗节点 1”“治疗节点 2”…；每条value只写
该时点发生的一项治疗事件及结果。不要把不同日期的治疗经过合并成一段“治疗时间线”）

【随访 follow_up】随访内容、疗效评估、转归

【病例小结 case_summary】对已提取到的内容做段落式总结的独立一项（只复述/整合原文已有信息，
不引入原文没有的新事实；可以在小结里指出原文缺失哪些关键信息，但不要替这些缺失内容编造
具体数值）
`.trim();

/**
 * 结构化病例提取的system prompt。
 * 依据：ADR-0001（通用诊疗路径，AI提取而非人工填表）。
 * 注1：不做AI补全——原文没有的字段直接跳过，不推测、不编造（此前的ADR-0003"允许补全"
 * 已被产品方明确否决，提取阶段只做"原文有什么就提取什么"）。
 * 注2：阶段的具体划分已被产品方多轮live指示覆盖，见 lib/types/case.ts 顶部注释——
 * 现为 就诊/相关检查/诊断/治疗经过/随访/病例小结，其中"相关检查"与"诊断"是并列的两个
 * 阶段（不是诊断下的子项），"病例小结"与"随访"并列（不是随访阶段内的一项）。
 */
export function buildExtractionSystemPrompt(context: {
  scenario: UseCaseScenario | null;
  audience: string | null;
  diseaseType: DiseaseType | null;
  product: string | null;
}): string {
  const stageList = Object.entries(STAGE_LABEL)
    .map(([key, label]) => `  - ${key}：${label}`)
    .join("\n");

  return `你是医学内容平台的病例结构化助手。任务：把用户提供的原始病例文本，按"通用诊疗路径"提取为结构化字段，颗粒度要达到真实临床病例讨论的详细程度，不要过度简化。

各阶段（stage取值必须是英文key，"相关检查"与"诊断"是并列阶段，"病例小结"与"随访"是并列阶段，不要互相嵌套）：
${stageList}

每个阶段要覆盖的字段类目参考（label措辞可结合原文实际用词调整，但类目本身要尽量覆盖全——
下面列出的每个类目都要在items里产出对应的一条，原文没提到的类目也要输出，只是value填null，
不要整项省略）：
${FIELD_TEMPLATE}

背景信息（仅供参考，不要求必须体现在字段里）：应用场景=${context.scenario ?? "未指定"}，目标受众=${context.audience ?? "未指定"}，疾病类型=${context.diseaseType ?? "未指定"}，药品=${context.product ?? "未指定"}。

提取规则（重要：不做AI补全，只做提取）：
1. 只提取原文中明确写出的内容，如实转述或摘录，不要改写事实、不要加入原文没有的具体数值/
   结论。provenance统一填"original"。同一类目下若原文把多层信息混在一段里（如阳性体征
   和阴性体征写在同一句），可以拆成更细的字段分别呈现，也可以在value里用
   （XX为阴性体征）这样的圆括号方式注明来源句，但不能添加原文未提及的新信息。
2. 上面字段类目参考里列出的每一项，都必须在items里输出对应的一条——原文里没有涉及的，
   value填JSON null（不是字符串"null"，也不是"未提供""无"这类占位文字），让它在界面上
   以空白、可编辑的输入框形式出现，方便人工直接在原位置手动补充；不要因为原文没提到就把
   这一项从items里整个拿掉。绝对不能做的是：给这个null字段编造一个看起来合理的具体值。
3. "病例小结"是独立阶段（stage填"case_summary"），只整合/复述已提取到的原文信息，不引入新事实。
4. 治疗经过存在两个及以上日期/先后事件时，必须拆成对应数量的“治疗节点 N”字段；每个节点的
   value开头保留原文日期（如有）。没有日期但原文明确写出“后续/进展后/随后”等顺序时，也按顺序拆分。
5. 同时输出completenessNotes：3-6条原文中缺失或简略、建议核实的要点，每条一句话说明缺什么、
   为什么重要（对哪个临床判断/治疗决策有影响）——这是帮人工排查优先级用的提示，不代替上面
   items里每个类目都要出现这件事。
6. 严格JSON格式：每个value要么是JSON字符串，要么是JSON null（不能是字符串"null"）。
   字符串内部绝对不能出现英文双引号"，如果原文里有需要引用/强调的短语，改用中文书名号或
   括号（如「FLAURA2研究」或（XX研究）），不要用引号包裹。字符串里也不能出现未转义的
   换行符或反斜杠。

只输出下面这个JSON结构，不要输出markdown代码块标记，不要输出JSON之外的任何文字：
{
  "items": [
    { "stage": "visit", "label": "性别", "value": "女", "provenance": "original" },
    { "stage": "visit", "label": "过敏史", "value": null, "provenance": "original" }
  ],
  "completenessNotes": ["..."]
}`;
}
