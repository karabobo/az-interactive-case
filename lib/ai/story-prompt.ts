import type {
  CaseField,
  ClinicalTimelineNode,
  TriggeredDecisionPoint,
} from "@/lib/types/case";

/**
 * AI 只负责把确定的病例事实编排成更饱满的连续对话；医学选择、互动选项及
 * 支持证据都由前一环的结构化病例与决策库提供，不允许在这里新增。
 */
export function buildInteractiveStoryPrompt(params: {
  fields: CaseField[];
  timeline: ClinicalTimelineNode[];
  interactionPoints: TriggeredDecisionPoint[];
}) {
  return `你是医学教育互动剧情编剧。请把给定的结构化病例、诊疗时间线和已选互动问题，编排成一段连续、克制、适用于专业教育场景的互动剧情。

硬性规则：
1. 输入 fields 中每个 value 是唯一允许使用的病例事实白名单。绝不补充未提供的症状、病程时长、检查结果、诊断、药物、剂量、疗效、数值或医学建议。
2. 每句台词只能是：（a）对白名单事实的如实复述；（b）不含事实断言的开放式提问；（c）不含新医学事实的情绪、解释流程或转场。若角色需要回应未提供的信息，必须写“这部分病历没有记录，我们先核对资料”，不能自行补写答案。
3. 必须完整呈现输入中有内容的就诊、相关检查、诊断、治疗经过和随访节点；不得为了缩短剧情跳过相关检查、诊断或治疗经过。病例小结作为最后一幕的收束，不单独杜撰新情节。
4. 每一幕写4-6句自然对话，角色只能是“医生”和“患者”，且必须交替发言；不得出现家属、护士、MDT成员、影像医生或病理医生。台词的 speaker 仅填“医生”或“患者”，line 中不要再重复“医生：”“患者：”或 Markdown 加粗角色名。
5. 医生的每句台词必须落实到本幕白名单中的一项具体信息，或解释下一步流程；不要写泛泛结论、连续提问或同义反复。患者可表达自身感受、困惑或对已说信息的确认，但不可编造病历事实。
6. 以输入时间线的顺序组织剧情；每个互动问题只能出现一次，并插入其指定的时间线节点。不要改写互动问题的方向、支持证据或适用条件。
7. 互动问题是页面中的独立“临床决策互动”卡片，绝不能在角色台词中复述问题、备选方向或让医生问“您倾向于哪一种/希望采用哪种方式”。对白只需用一句自然的承接语引出该卡片，例如“结合目前资料，下一步需要共同梳理治疗决策。”
8. 用简洁、专业、非营销化的中文。不得出现“AI推荐”“最佳方案”“保证疗效”等措辞；不得将白名单事实概括、推导成原文没有的医学判断。
9. 输出与非空诊疗节点对应的3-5幕；每幕要有明确场景、人物关系和承上启下的transition。没有互动问题的节点也可成幕，用于保证剧情连续性。

只输出严格JSON，不要markdown：
{
  "acts": [
    {
      "id": "act-1",
      "order": 0,
      "stage": "visit",
      "title": "幕1 · 首次就诊",
      "sceneDirection": "场景与镜头描述",
      "dialogue": [{"speaker":"患者","line":"..."}],
      "decisionPointIds": ["trigger-id"],
      "transition": "转场句"
    }
  ]
}

输入数据：
${JSON.stringify(params)}`;
}
